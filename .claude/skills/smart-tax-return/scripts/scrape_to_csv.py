#!/usr/bin/env python3
"""CSVエクスポート機能が無いサイトの履歴をCSVに起こすためのテンプレート。

楽天PointClub や メルカリ のように公式のCSV出力が無いサイトでは、
画面のテキストを取得して行を起こすしかない。その定型処理をまとめたもの。

使い方は「rows を書き換えて実行する」だけ。
get_page_text で取った各ページのテキストを読んで、1行1タプルに起こしていく。

いちばん大事なのは検算。ページを1枚取りこぼしても完成してしまうので、
サイトが表示している総件数（"全163件" など）を EXPECTED_COUNT に入れておくと、
一致しなければエラーで止まる。
"""

import csv
import sys

# ---------------------------------------------------------------
# 設定
# ---------------------------------------------------------------

OUT_PATH = "/sessions/<session>/mnt/outputs/出力ファイル名.csv"

# サイトが表示していた総件数。分からなければ None。
# 入れておくと取りこぼしを検出できるので、可能な限り入れる。
EXPECTED_COUNT = None

# Excelで開いたときに日本語が化けないよう BOM 付きUTF-8で書く
ENCODING = "utf-8-sig"

HEADER = ["日付", "サービス", "内容", "ランクアップ対象", "区分", "ポイント数", "備考"]

# ---------------------------------------------------------------
# データ
# get_page_text の結果を見ながらここを埋めていく。
# 日付は昇順・降順どちらでもよいが、サイトの並び順のままにしておくと
# 元ページと突き合わせやすい。
# ---------------------------------------------------------------

rows = [
    # ("2026/06/30", "キャンペーン", "……", "", "獲得(期間限定)", "1000", "……"),
]

# ---------------------------------------------------------------

def main():
    if EXPECTED_COUNT is not None and len(rows) != EXPECTED_COUNT:
        sys.exit(
            f"件数が合いません: rows={len(rows)} / サイト表示={EXPECTED_COUNT}\n"
            f"ページの取りこぼしがないか確認してください。"
        )

    with open(OUT_PATH, "w", newline="", encoding=ENCODING) as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(rows)

    print(f"wrote {OUT_PATH}  rows={len(rows)}")

    # 簡易サマリ。日付範囲が想定した四半期に収まっているかの確認に使う。
    if rows:
        dates = [r[0] for r in rows]
        print(f"日付範囲: {min(dates)} 〜 {max(dates)}")


if __name__ == "__main__":
    main()
